# ── Helper functions ──────────────────────────────────────────────────────

def get_tickers(sectors: list[str] | None = None) -> list[str]:
    constituents = SP500_CONSTITUENTS
    if sectors:
        constituents = [c for c in constituents if c.sector in sectors]
    return [c.ticker for c in constituents]


def get_dataframe() -> pd.DataFrame:
    return pd.DataFrame([{
        "ticker":         c.ticker,
        "name":           c.name,
        "sector":         c.sector,
        "sub_industry":   c.sub_industry,
        "weight_pct":     c.weight_pct,
        "beta":           float(c.beta) if isinstance(c.beta, str) else c.beta,
        "market_cap_cat": c.market_cap_cat,
    } for c in SP500_CONSTITUENTS])


def sector_summary() -> pd.DataFrame:
    df = get_dataframe()
    return (
        df.groupby("sector")
          .agg(n_stocks=("ticker","count"), total_weight=("weight_pct","sum"))
          .reset_index()
          .sort_values("total_weight", ascending=False)
    )


def fetch_live_constituents() -> list[str]:
    """Fetch latest S&P 500 tickers from Wikipedia."""
    try:
        tables = pd.read_html("https://en.wikipedia.org/wiki/List_of_S%26P_500_companies")
        return tables[0]["Symbol"].str.replace(".", "-", regex=False).tolist()
    except Exception as e:
        print(f"Live fetch failed ({e}); using hardcoded list")
        return get_tickers()


